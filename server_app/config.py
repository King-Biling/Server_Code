SCAN_SPEED = 0.05                 # 扫描横向速度 (m/s)
SCAN_AMPLITUDE = 0.08             # 扫描单侧幅度 (m)，即左右各移 8cm
SCAN_HALF_PERIOD = 8.0            # 扫描半周期 (秒)，左右各 8 秒
SCAN_TAG_LOCK_FRAMES = 3          # 连续检测到Tag的帧数，确认锁定后停止扫描
SCAN_MAX_DURATION = 30.0          # 扫描最大持续时间 (秒)，超时放弃扫描

# ------------------------------------------------------------------------------
