# -*- coding: utf-8 -*-
"""
================================================================================
 模块名称: server_app.config
 模块职责: 全局常量与运行时可调参数集中定义
--------------------------------------------------------------------------------
 本模块存放整个服务器端使用到的全部“配置量”，分为两类：

   1. 常量类：端口、拓扑默认值、AprilTag 物理尺寸等，运行期间不变。
   2. 可调参数类：PREP 重试超时、STEP 握手超时、末端制导增益/阈值等，
      可能被 /api/reconstruct/params 接口在运行时重新赋值。

 重要约定（保持行为不变的关键）:
   对于“会被重新赋值”的参数（如 PREP_RETRY_TIMEOUT、GUIDE_FUNNEL_Y_THRESHOLD），
   其它模块必须以 `config.PREP_RETRY_TIMEOUT` 的形式访问，
   禁止使用 `from config import PREP_RETRY_TIMEOUT` 拷贝取值，
   否则运行时对该参数的修改无法被其它模块看到。

 编码格式: UTF-8（无 BOM）
================================================================================
"""

import os

# ------------------------------------------------------------------------------
# 目录与路径
# ------------------------------------------------------------------------------
# 说明：原单体文件位于工程根目录，使用 os.path.dirname(__file__) 定位工程内的
# logs / templates / 标定文件等资源。拆分为子包后，本模块位于 server_app/ 下，
# 因此工程根目录需取本文件所在目录的上一级，保证所有资源路径与原实现完全一致。
PACKAGE_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(PACKAGE_DIR, os.pardir))

# 视觉引擎子模块目录（Car_vision_system）
VISION_MODULE_DIR = os.path.join(PROJECT_ROOT, "Car_vision_system")

# 日志与位姿数据目录名（相对工程根目录）
POSE_SAVE_DIRNAME = "pose_data"
LOG_DIRNAME = "logs"
# 自动归档（自动下载）目录，位于 logs 下
LOG_ARCHIVE_DIRNAME = os.path.join(LOG_DIRNAME, "auto_downloads")
# 自动归档间隔（秒），默认每 10 分钟归档一次
LOG_ARCHIVE_INTERVAL_S = 10 * 60

# ------------------------------------------------------------------------------
# 网络端口
# ------------------------------------------------------------------------------
UDP_HOST = "0.0.0.0"      # UDP 遥测/指令服务器监听地址
UDP_PORT = 8080           # UDP 遥测/指令服务器监听端口
WEB_PORT = 5000           # Flask Web 控制台端口
BROADCAST_PORT = 8081     # 子网广播端口
CAR_COMMAND_PORT = 8081   # 回包固定发往的小车监听端口

# ------------------------------------------------------------------------------
# 广播默认参数（注意：以下三个量会被 HTTP 接口重新赋值，见 state 模块说明）
# ------------------------------------------------------------------------------
# 说明：broadcast_enabled / broadcast_interval / broadcast_group_size 属于
# “运行时可变状态”，为便于跨模块共享与重新赋值，统一放在 state 模块中。

# ------------------------------------------------------------------------------
# 重构（reconstruct）相关常量
# ------------------------------------------------------------------------------
# 拼接位置标签（首车=HEAD，其后依次 MID2 / MID3 / TAIL）
RECONSTRUCT_POS_LABELS = ["HEAD", "MID2", "MID3", "TAIL"]
# 重构事件日志在内存中保留的最大条数
MAX_RECONSTRUCT_EVENTS = 120

# ------------------------------------------------------------------------------
# PREP 阶段重试策略（秒）——可调参数
# ------------------------------------------------------------------------------
PREP_RETRY_TIMEOUT = 3.0          # 某车超过该时长未 PREP_OK 触发重试
PREP_RETRY_PREP_INTERVAL = 1.0    # 前车可见时，重发 PREP 的最小间隔
PREP_RETRY_ORDER_INTERVAL = 2.0   # 前车不可见时，重发 ORDER 的最小间隔
PREP_OK_VALID_WINDOW = 3.0        # PREP_OK 的有效时间窗口

# ------------------------------------------------------------------------------
# STEP / IMG 握手超时（秒）——常量
# ------------------------------------------------------------------------------
STEP_ACK_TIMEOUT = 1.5            # 下发 STEP 后等待 STEP_ACK 的超时
FIRST_IMAGE_TIMEOUT = 1.5        # STEP_ACK 后等待首帧图像的超时
STEP_RETRY_MAX = 3               # STEP 最大重试次数
ASM_STAGGER_WAIT_GRACE = 2.5     # 收到 ASM_STAGGER_WAIT 诊断后的额外宽限时间

# ------------------------------------------------------------------------------
# 末端制导参数
# ------------------------------------------------------------------------------
GUIDE_SPEED_LIMIT = 0.105        # 线速度限幅 (m/s)
# 误差输入单位为 cm，因此增益按 cm 缩放
GUIDE_P_GAIN_X = 0.0035          # 前进误差 P 增益
GUIDE_P_GAIN_Y = 0.0035          # 横向误差 P 增益
GUIDE_P_GAIN_YAW = 0.03          # 航向角 P 增益（输入为度数，故取较小值）
GUIDE_MAX_VZ = 0.4               # 最大旋转角速度 (rad/s)
# 漏斗解耦阈值：横向偏差(cm)或航向偏差(deg)超过阈值时，先整列、暂缓前进。
# 判定对象必须是“横向 error_y / 航向 yaw”，而非“纵向 error_x”，
# 否则一开始离得远(纵向大)就会永远禁止前进，导致小车停在准备位不动。
GUIDE_FUNNEL_Y_THRESHOLD = 4.0   # cm（横向）——可调参数
GUIDE_FUNNEL_YAW_THRESHOLD = 4.0 # deg（航向）——可调参数

# ------------------------------------------------------------------------------
# 横向扫描参数（进入制导阶段后持续无Tag时，小车左右横移搜索标签）
# ------------------------------------------------------------------------------
